function resolveLang(language) {
  return brandingI18n[language] ? language : 'vi';
}

export function getBrandingCopy(language = 'vi') {
  return brandingI18n[resolveLang(language)];
}

export function getBrandingServicePackages(language = 'vi') {
  return getBrandingCopy(language).servicePackages;
}

export function getLandingPageStatusMeta(status, language = 'vi') {
  const copy = getBrandingCopy(language);
  const num = Number(status);
  return {
    label: copy.statusLabels[num] || copy.statusLabels[0],
    ...(copy.statusStyle[num] || copy.statusStyle[0]),
  };
}

export function formatBrandingDate(value, language = 'vi') {
  if (!value) return '—';
  try {
    return new Date(value).toLocaleString(getDateLocale(language));
  } catch {
    return '—';
  }
}

export function formatBrandingJobLabel(job, language = 'vi') {
  if (!job) return '';
  const code = job.jobCode ? `[${job.jobCode}] ` : '';
  const title = getLocalizedJobTitle(job, language) || getBrandingCopy(language).intake.untitledJob;
  return `${code}${title}`;
}

export function getBrandingPageTypeLabel(page, language = 'vi') {
  const copy = getBrandingCopy(language);
  if (page?.builderType === 'company') return copy.pageTypeCompany;
  return copy.pageTypeRecruitment;
}
