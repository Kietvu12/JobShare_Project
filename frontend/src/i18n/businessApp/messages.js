const CREDIT_STATUS_STYLE = {
  pending: { bg: '#dbeafe', color: '#2563eb' },
  approved: { bg: '#dcfce7', color: '#16a34a' },
  rejected: { bg: '#fee2e2', color: '#dc2626' },
  cancelled: { bg: '#f1f5f9', color: '#64748b' },
};

export function getCreditRequestStatusStyle(status, language = 'vi') {
  const key = String(status || 'pending').toLowerCase();
  const labels = getMessagesCopy(language).creditPanel?.status || messagesI18n.vi.creditPanel.status;
  const visual = CREDIT_STATUS_STYLE[key] || CREDIT_STATUS_STYLE.pending;
  return { label: labels[key] || labels.pending, ...visual };
}

export function formatCreditPanelDateTime(value, language = 'vi') {
  if (!value) return '—';
  try {
    const lang = resolveLang(language);
    const locale = lang === 'ja' ? 'ja-JP' : lang === 'en' ? 'en-US' : 'vi-VN';
    return new Date(value).toLocaleString(locale, { dateStyle: 'short', timeStyle: 'short' });
  } catch {
    return '—';
  }
}

export function formatCreditPanelNumber(n, language = 'vi') {
  const lang = resolveLang(language);
  const locale = lang === 'ja' ? 'ja-JP' : lang === 'en' ? 'en-US' : 'vi-VN';
  return Number(n || 0).toLocaleString(locale);
}

export function getMessagesCopy(language = 'vi') {
  return messagesI18n[resolveLang(language)] || messagesI18n.vi;
}

export function getMessageMainTabs(language = 'vi') {
  const m = getMessagesCopy(language);
  return [
    { label: m.tabs.ctv, shortLabel: m.tabs.ctvShort, key: 'ctv' },
    { label: m.tabs.ws, shortLabel: m.tabs.wsShort, key: 'ws' },
  ];
}

export function getMessageWsViews(language) {
  const v = getMessagesCopy(language).wsViews;
  return [
    { key: 'chat', labelKey: 'chat' },
    { key: 'credit', labelKey: 'credit' },
    { key: 'credit-history', labelKey: 'creditHistory' },
  ].map(({ key, labelKey }) => ({ key, label: v[labelKey] }));
}

export function getWsChatLocale(language = 'vi') {
  const lang = resolveLang(language);
  if (lang === 'ja') return 'ja-JP';
  if (lang === 'en') return 'en-US';
  return 'vi-VN';
}

