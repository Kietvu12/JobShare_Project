export function getPerformanceRequestContextLabel(candidate, language = 'vi') {
  const ctx = getScoutWorkspaceCopy(language).performanceContext;
  const position = candidate?.desiredPosition || candidate?.jobCategory?.name;
  const skills = getScoutSkillTags(candidate).slice(0, 3).join(', ');
  if (position && skills) return ctx.positionWithSkills(position, skills);
  if (position) return ctx.positionOnly(position);
  if (skills) return ctx.skillsOnly(skills);
  return ctx.fallback;
}

export function getScoutJobOptionLabel(job, language = 'vi') {
  if (!job) return '';
  const base = getLocalizedJobTitle(job, language) || `JD #${job.id}`;
  return job.jobCode ? `${job.jobCode} · ${base}` : base;
}

export function formatScoutLocaleNumber(n, language = 'vi') {
  return Number(n || 0).toLocaleString(getDateLocale(language));
}
