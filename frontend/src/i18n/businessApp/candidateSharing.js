function formatListingReferralFeeFallback(listing, language) {
  const type = listing.referralFeeType || 'percent';
  const value = Number(listing.referralFeeValue || 0);
  const lang = resolveLang(language);
  const locale = getDateLocale(lang);
  if (type === 'percent') {
    if (lang === 'en') return `${value}% of first-year income`;
    if (lang === 'ja') return `初年度年収の${value}%`;
    return `${value}% thu nhập năm đầu`;
  }
  const suffix = lang === 'en' ? ' JPY (fixed)' : lang === 'ja' ? ' 円（固定）' : 'đ (cố định)';
  return `${value.toLocaleString(locale)}${suffix}`;
}

/** Phí giới thiệu hiển thị trên bảng/chi tiết Sàn CTV — theo ngôn ngữ UI, không dùng feeLabel API (VI). */
export function getMarketplaceListingReferralFeeLabel(listing, language = 'vi') {
  const emDash = getCandidateSharingCopy(language).common.emDash;
  if (!listing) return emDash;
  const contact = formatJobCommissionSummary(null, language);
  const fromJob = formatJobCommissionSummary(listing.job, language);
  if (fromJob && fromJob !== contact) return fromJob;
  return formatListingReferralFeeFallback(listing, language);
}

export function formatMarketplaceJobPickerLabel(job, language = 'vi') {
  if (!job) return '';
  const title = getLocalizedJobTitle(job, language) || `Job #${job.id}`;
  const code = job.jobCode || job.job_code || '';
  return code ? `${title} (${code})` : title;
}

export function getApplicationStatusLabelForMarketplace(statusCode, language = 'vi') {
  const code = Number(statusCode);
  for (const col of getKanbanColumns(language)) {
    if (col.statuses?.includes(code)) return col.label;
  }
  return getCandidateSharingCopy(language).common.emDash;
}

export function getNominationStatusBadgeStyle(statusCode) {
  const code = Number(statusCode);
  if ([14, 15].includes(code)) return { bg: '#d1fae5', color: '#059669' };
  if ([11, 12].includes(code)) return { bg: '#ede9fe', color: '#7c3aed' };
  if (code === 2) return { bg: '#dbeafe', color: '#2563eb' };
  if ([3, 5, 7, 8, 9].includes(code)) return { bg: '#ede9fe', color: '#7c3aed' };
  return { bg: '#f1f5f9', color: '#64748b' };
}

export function formatPlatformStat(value, suffix = '', language = 'vi') {
  const locale = getDateLocale(language);
  if (value == null || Number.isNaN(Number(value))) return getCandidateSharingCopy(language).common.emDash;
  return `${Number(value).toLocaleString(locale)}${suffix}`;
}
